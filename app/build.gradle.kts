abstract class GenerateGitHashTask : DefaultTask() {

    @get:Optional
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val headFile: RegularFileProperty

    @get:Optional
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val headsDir: DirectoryProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val head = if (headFile.isPresent) headFile.get().asFile else null

        val hash = try {
            if (head != null && head.exists()) {
                val headContent = head.readText().trim()
                if (headContent.startsWith("ref:")) {
                    val refPath = headContent.substring(5)
                    val commitFile = File(head.parentFile, refPath)
                    if (commitFile.exists()) commitFile.readText().trim() else ""
                } else headContent
            } else ""
        } catch (_: Throwable) {
            ""
        }.take(7)

        val outFile = outputDir.file("git-hash.txt").get().asFile
        outFile.parentFile.mkdirs()
        outFile.writeText(hash)
    }
}

val generateGitHash = tasks.register<GenerateGitHashTask>("generateGitHash") {
    val gitDir = layout.projectDirectory.dir("../.git")
    if (gitDir.asFile.exists()) {
        headFile.set(gitDir.file("HEAD"))
        headsDir.set(gitDir.dir("refs/heads"))
    }

    outputDir.set(layout.buildDirectory.dir("generated/git"))
}

